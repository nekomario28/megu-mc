/// Binary-search [`EXTRA_GLYPHS`] for `c`. Returns the table index (the atlas
/// tile pair is `EXTRA_GLYPH_TILE_BASE + 2*idx`) plus the entry's bitmap.
pub fn lookup_extra(c: char) -> Option<(usize, GlyphBitmap)> {
    let cp = c as u32;
    if cp > u32::from(u16::MAX) {
        return None;
    }
    let mut lo = 0usize;
    let mut hi = EXTRA_GLYPHS.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        let (key, cells, tiles) = &EXTRA_GLYPHS[mid];
        match u32::from(*key).cmp(&cp) {
            std::cmp::Ordering::Less => lo = mid + 1,
            std::cmp::Ordering::Greater => hi = mid,
            std::cmp::Ordering::Equal => {
                return Some((
                    mid,
                    GlyphBitmap {
                        cells: *cells,
                        tiles: *tiles,
                    },
                ));
            }
        }
    }
    None
}

/// `true` when `cp` sits in a Unicode East-Asian full-width range — used to
/// pick the wide fallback box for unmapped codepoints so they still advance
/// two cells and never overlap neighbors.
pub fn is_fullwidth_codepoint(cp: u32) -> bool {
    matches!(
        cp,
        0x1100..=0x115F          // Hangul Jamo
            | 0x2E80..=0xA4CF    // CJK Radicals .. Yi
            | 0xAC00..=0xD7A3    // Hangul Syllables
            | 0xF900..=0xFAFF    // CJK Compatibility Ideographs
            | 0xFE30..=0xFE6F    // CJK Compatibility Forms / small variants
            | 0xFF00..=0xFF60    // Fullwidth Forms
            | 0xFFE0..=0xFFE6    // Fullwidth signs
            | 0x20000..=0x3FFFD  // CJK Extension B and beyond
    )
}
