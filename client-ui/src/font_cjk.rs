//! Extended clean-room bitmap glyph coverage for [`crate::draw`]: every
//! Hiragana (`U+3041..=U+3096`), every Katakana (`U+30A1..=U+30FC`), the CJK
//! punctuation set used by the bilingual UI (`、。「」『』【】・ー〜！？（）＆`),
//! all Hangul/Cyrillic/Latin-Extended codepoints needed by the locale
//! autonyms, and the full Kanji subset covering every `ja_jp`/`zh_cn`/`zh_tw`
//! label the crate renders.
//!
//! Every glyph here is original clean-room pixel art authored for this crate
//! on a 16-column × 8-row canvas for full-width codepoints (the "double
//! cell": a CJK character advances two [`crate::draw::GLYPH_SIZE`] cells) or
//! the standard 8×8 cell for half-width codepoints. The art lives in-source
//! as `#`/`.` rows compiled by `const fn`, exactly like the ASCII face —
//! no font binaries, no third-party font data.
//!
//! The module also provides [`GlyphAtlas`], a pure-`std` runtime glyph map a
//! user can fill from any external [GNU Unifont](https://unifoundry.com)
//! `.hex` font pack (`CODEPOINT:HEXBITS`, 8×16 or 16×16) via
//! [`GlyphAtlas::load_unifont_hex`] — strictly size- and format-bounded and
//! fail-closed on malformed input — and install with
//! [`install_external_font`] so unmapped codepoints render instead of tofu.

use std::collections::BTreeMap;
use std::fmt;
use std::sync::RwLock;

/// Glyph raster data: one or two adjacent 8×8 tiles, painted left-to-right.
/// `cells` is the width class in [`crate::draw::GLYPH_SIZE`] columns (1 =
/// half width, 2 = full width); for `cells == 1`, `tiles[1]` is all zero.
/// The rendered advance is [`crate::draw::glyph_advance`] — two-cell art
/// squeezes to [`crate::draw::FULLWIDTH_PX`] px.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct GlyphBitmap {
    /// Source width in 8-px cells (1 half-width, 2 full-width).
    pub cells: u8,
    /// `tiles[0]` = left cell, `tiles[1]` = right cell (zero for half-width).
    pub tiles: [[u8; 8]; 2],
}

/// Compile a 16-column × 8-row `#`/`.` glyph into its two 8×8 tiles.
const fn gw(rows: [&str; 8]) -> [[u8; 8]; 2] {
    let mut out = [[0u8; 8]; 2];
    let mut i = 0;
    while i < 8 {
        let bytes = rows[i].as_bytes();
        let mut j = 0;
        while j < 16 && j < bytes.len() {
            if bytes[j] == b'#' {
                if j < 8 {
                    out[0][i] |= 0x80 >> j;
                } else {
                    out[1][i] |= 0x80 >> (j - 8);
                }
            }
            j += 1;
        }
        i += 1;
    }
    out
}

/// Compile an 8-column × 8-row `#`/`.` glyph into a left tile + empty right
/// tile (half-width glyph in the shared two-tile representation).
const fn gn(rows: [&str; 8]) -> [[u8; 8]; 2] {
    let mut out = [[0u8; 8]; 2];
    let mut i = 0;
    while i < 8 {
        let bytes = rows[i].as_bytes();
        let mut j = 0;
        while j < 8 && j < bytes.len() {
            if bytes[j] == b'#' {
                out[0][i] |= 0x80 >> j;
            }
            j += 1;
        }
        i += 1;
    }
    out
}

