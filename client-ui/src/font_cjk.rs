/// a static reason. Everything is checked before use, so loading either
/// returns a complete atlas or a descriptive error — never a partial map.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct FontPackError {
    /// 1-based offending line, or 0 for whole-file limit failures.
    pub line: usize,
    /// Static description of the violated rule.
    pub reason: &'static str,
}

impl fmt::Display for FontPackError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        if self.line == 0 {
            write!(f, "font pack rejected: {}", self.reason)
        } else {
            write!(f, "font pack line {}: {}", self.line, self.reason)
        }
    }
}

impl std::error::Error for FontPackError {}

fn hex_val(b: u8) -> Option<u32> {
    match b {
        b'0'..=b'9' => Some(u32::from(b - b'0')),
        b'a'..=b'f' => Some(u32::from(b - b'a' + 10)),
        b'A'..=b'F' => Some(u32::from(b - b'A' + 10)),
        _ => None,
    }
}

/// Full-height Unifont source rows: `cells` columns of 8 px (1 or 2)
/// and the 16 source scanlines, MSB = leftmost pixel. Half-width (8×16)
/// glyphs keep their ink left-justified in the high byte so
/// `row & (0x8000 >> col)` is one uniform bit test for both widths.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct GlyphRows16 {
    /// 1 = 8×16 half-width, 2 = 16×16 full-width.
    pub cells: u8,
    /// The 16 scanlines, left-justified.
    pub rows: [u16; 16],
}

impl GlyphRows16 {
    /// Deterministic 2:1 vertical decimation into the built-in 8-row
    /// canvas: adjacent source rows are pairwise OR'd (no stroke is
    /// dropped); the 16-bit row splits into the two tiles.
    pub fn decimate(&self) -> GlyphBitmap {
        let mut tiles = [[0u8; 8]; 2];
        for (dst, pair) in self.rows.as_chunks::<2>().0.iter().enumerate() {
            let row = pair[0] | pair[1];
            tiles[0][dst] = (row >> 8) as u8;
            tiles[1][dst] = row as u8;
        }
        GlyphBitmap {
            cells: self.cells,
            tiles,
        }
    }

    /// `true` when source pixel `(col, row)` is set.
    pub fn lit(&self, col: u32, row: u32) -> bool {
        (col < u32::from(self.cells.max(1)) * 8 && row < 16)
            && self.rows[row as usize] & (0x8000u16 >> col) != 0
    }
}

/// Runtime glyph map built from an external Unifont-style `.hex` pack
/// plus an optional vanilla `ascii.png` cell table. Glyphs are stored
/// un-squashed as full 16-row [`GlyphRows16`]; the built-in 8-row canvas
/// form is produced on demand via [`GlyphRows16::decimate`].
#[derive(Clone, Debug, Default)]
pub struct GlyphAtlas {
    glyphs: BTreeMap<u32, GlyphRows16>,
    /// Vanilla `ascii.png` 8×8 cells indexed by raw codepoint 0x00–0x7F
    /// (cell index = row*16+col of the png's 16×16 grid).
    ascii: Option<Box<[[u8; 8]; 128]>>,
}

impl GlyphAtlas {
    /// Number of loaded glyphs.
    pub fn glyph_count(&self) -> usize {
        self.glyphs.len()
    }

    /// `true` when the atlas holds a glyph for `c`.
    pub fn covers(&self, c: char) -> bool {
        self.glyphs.contains_key(&(c as u32))
    }

    /// Loaded bitmap for `c` decimated to the built-in 8-row canvas —
    /// the compatibility view used for advances and pack diagnostics.
    pub fn glyph_bitmap(&self, c: char) -> Option<GlyphBitmap> {
        self.glyphs.get(&(c as u32)).map(GlyphRows16::decimate)
    }

    /// Loaded full 16-row glyph for `c`, if present — the un-squashed
    /// Unifont source the renderers sample directly.
    pub fn unifont_glyph(&self, c: char) -> Option<GlyphRows16> {
        self.glyphs.get(&(c as u32)).copied()
    }

    /// Install the vanilla `ascii.png` table: 128 8×8 bitmaps indexed by
    /// raw codepoint (cell `row*16+col` of the png grid = codepoint).
    pub fn set_ascii_bitmap(&mut self, cells: Box<[[u8; 8]; 128]>) {
        self.ascii = Some(cells);
    }

    /// `true` when a vanilla `ascii.png` table is installed.
    pub fn has_ascii_bitmap(&self) -> bool {
        self.ascii.is_some()
    }

    /// Fold every glyph of `other` into `self` — later wins per
    /// codepoint, so patch packs (e.g. `unifont_jp_patch`) loaded after a
    /// base pack (`unifont_all_no_pua`) override just their codepoints,
    /// exactly like the vanilla font provider chain.
    pub fn absorb(&mut self, other: GlyphAtlas) {
        for (cp, glyph) in other.glyphs {
            self.glyphs.insert(cp, glyph);
        }
        if other.ascii.is_some() {
            self.ascii = other.ascii;
        }
    }

    /// 8×8 bitmap for a U+0000–U+007F codepoint from the installed
    /// vanilla `ascii.png` table, if loaded.
    pub fn ascii_glyph(&self, c: char) -> Option<[u8; 8]> {
        let cp = c as u32;
        self.ascii
            .as_ref()
            .and_then(|t| (cp < 128).then(|| t[cp as usize]))
    }

    /// Insert (or replace) one glyph in the built-in 8-row canvas form —
    /// rows are duplicated 1:2 into the full-height store, so the
    /// inserted bitmap round-trips exactly through `glyph_bitmap`.
    pub fn insert(&mut self, c: char, bitmap: GlyphBitmap) {
        let mut rows = [0u16; 16];
        for (dst, pair) in rows.as_chunks_mut::<2>().0.iter_mut().enumerate() {
            let lo = if bitmap.cells >= 2 {
                bitmap.tiles[1][dst]
            } else {
                0
            };
            let row = ((bitmap.tiles[0][dst] as u16) << 8) | lo as u16;
            pair[0] = row;
            pair[1] = row;
        }
        self.glyphs.insert(
            c as u32,
            GlyphRows16 {
                cells: bitmap.cells,
                rows,
            },
        );
    }

    /// Pixel width of `text` at `scale` under this atlas: characters the
    /// atlas covers advance by their loaded width, everything else by the
    /// built-in lookup (`\n` resets the line).
    pub fn measure_text_px(&self, text: &str, scale: u32) -> (u32, u32) {
        let mut lines = 0u32;
        let mut width = 0u32;
        let mut line = 0u32;
        for c in text.chars() {
            if c == '\n' {
                width = width.max(line);
                line = 0;
                lines += 1;
                continue;
            }
            let cells = match self.glyph_bitmap(c) {
                Some(g) => g.cells,
                None => crate::draw::glyph_bitmap(c).cells,
            };
            // Same rendered advance as the runtime pipeline
            // (`draw::glyph_advance`): full-width art renders at
            // `FULLWIDTH_PX`, half-width at `GLYPH_SIZE`.
            line += if cells >= 2 {
                crate::draw::FULLWIDTH_PX
            } else {
                crate::draw::GLYPH_SIZE
            } * scale;
        }
        (width.max(line), (lines + 1) * crate::draw::GLYPH_SIZE * scale)
    }

    /// Parse a GNU Unifont `.hex` pack: one `CODEPOINT:HEXBITS` record per
    /// line where `HEXBITS` is 32 nibbles (8×16 half-width) or 64 nibbles
    /// (16×16 full-width). Rows are big-endian bit strings exactly like the
    /// built-ins. Blank lines are skipped; every other deviation — bad
    /// digits, wrong hex length, out-of-BMP codepoint, duplicate entry,
    /// oversized input — is a hard error.
    pub fn load_unifont_hex(text: &str) -> Result<Self, FontPackError> {
        if text.len() > MAX_UNIFONT_HEX_BYTES {
            return Err(FontPackError {
                line: 0,
                reason: "input exceeds the 8 MiB pack bound",
            });
        }
        let mut glyphs = BTreeMap::new();
        for (idx, raw) in text.lines().enumerate() {
            let line = idx + 1;
            let trimmed = raw.trim();
            if trimmed.is_empty() {
                continue;
            }
            if trimmed.len() > MAX_UNIFONT_LINE {
                return Err(FontPackError {
                    line,
                    reason: "line exceeds the 96-char bound",
                });
            }
            let (cp_text, bits_text) = trimmed.split_once(':').ok_or(FontPackError {
                line,
                reason: "missing ':' separator",
            })?;
            if cp_text.is_empty() || cp_text.len() > 6 {
                return Err(FontPackError {
                    line,
                    reason: "codepoint must be 1-6 hex digits",
                });
            }
            let mut cp = 0u32;
            for &b in cp_text.as_bytes() {
                let Some(v) = hex_val(b) else {
                    return Err(FontPackError {
                        line,
                        reason: "non-hex codepoint digit",
                    });
                };
                cp = cp * 16 + v;
            }
            if cp > 0xFFFF {
                return Err(FontPackError {
                    line,
                    reason: "codepoint outside the BMP",
                });
            }
            let nibble = bits_text.len();
            let (cols, expected) = match nibble {
                32 => (1u8, 32usize),
                64 => (2u8, 64usize),
                _ => {
                    return Err(FontPackError {
                        line,
                        reason: "hexbits must be 32 (8x16) or 64 (16x16) digits",
                    })
                }
            };
            debug_assert_eq!(nibble, expected);
            // Unifont rows are `cols*2` hex digits each (8 or 16 px wide),
            // 16 rows top-to-bottom — stored un-squashed, left-justified
            // in u16 so bit `0x8000 >> col` is one uniform test.
            let mut rows = [0u16; 16];
            let row_digits = cols as usize * 2;
            for (src_row, chunk) in bits_text.as_bytes().chunks(row_digits).enumerate() {
                let mut bits = [0u8; 2];
                for (col_idx, &hb) in chunk.iter().enumerate() {
                    let Some(v) = hex_val(hb) else {
                        return Err(FontPackError {
                            line,
                            reason: "non-hex digit in hexbits",
                        });
                    };
                    bits[col_idx / 2] = (bits[col_idx / 2] << 4) | (v as u8 & 0xF);
                }
                if src_row < 16 {
                    rows[src_row] = ((bits[0] as u16) << 8) | bits[1] as u16;
                }
            }
            let glyph = GlyphRows16 { cells: cols, rows };
            if glyphs.insert(cp, glyph).is_some() {
                return Err(FontPackError {
                    line,
                    reason: "duplicate codepoint",
                });
            }
            if glyphs.len() > MAX_UNIFONT_GLYPHS {
                return Err(FontPackError {
                    line: 0,
                    reason: "glyph count exceeds the BMP bound",
                });
            }
        }
        Ok(Self {
            glyphs,
            ascii: None,
        })
    }

    /// Rasterize `text` (single line) at `scale` into a fresh RGBA buffer:
    /// a diagnostic for pack authors — the returned `(width, height, rgba)`
    /// paints every covered glyph white-on-transparent so diffs between two
    /// packs are directly comparable. Glyphs the atlas misses fall back to
    /// the built-in tables (or the fallback box).
    pub fn rasterize_text_px(&self, text: &str, scale: u32) -> (u32, u32, Vec<u8>) {
        let scale = scale.max(1);
        let text = text.split('\n').next().unwrap_or("");
        let mut width = 0u32;
        for c in text.chars() {
            let cells = match self.glyph_bitmap(c) {
                Some(g) => g.cells,
                None => crate::draw::glyph_bitmap(c).cells,
            };
            width += if cells >= 2 {
                crate::draw::FULLWIDTH_PX
            } else {
                crate::draw::GLYPH_SIZE
            } * scale;
        }
        let height = crate::draw::GLYPH_SIZE * scale;
        let mut rgba = vec![0u8; width as usize * height as usize * 4];
        let mut cx = 0i32;
        for c in text.chars() {
            let g = match self.glyph_bitmap(c) {
                Some(g) => g,
                None => crate::draw::glyph_bitmap(c),
            };
            let cells = u32::from(g.cells.max(1));
            let (src_w, adv) = if g.cells >= 2 {
                (cells * 8, crate::draw::FULLWIDTH_PX)
            } else {
                (8, crate::draw::GLYPH_SIZE)
            };
            for (tile_idx, tile) in g.tiles.iter().enumerate() {
                if tile_idx >= g.cells as usize {
                    break;
                }
                for (row, bits) in tile.iter().enumerate() {
                    for col in 0..8u32 {
                        if (bits & (0x80 >> col)) == 0 {
                            continue;
                        }
                        // Full-width source art squeezes 16→12 dst px,
                        // matching `Frame::glyph_cell`'s floor merge.
                        let dst = (tile_idx as u32 * 8 + col) * adv / src_w;
                        for dy in 0..scale {
                            for dx in 0..scale {
                                let px = cx + dst as i32 * scale as i32 + dx as i32;
                                let py = row as i32 * scale as i32 + dy as i32;
                                if px < 0 || py < 0 {
                                    continue;
                                }
                                let (px, py) = (px as u32, py as u32);
                                if px >= width || py >= height {
                                    continue;
                                }
                                let o = ((py * width + px) * 4) as usize;
                                rgba[o..o + 4].copy_from_slice(&[0xff, 0xff, 0xff, 0xff]);
                            }
                        }
                    }
                }
            }
            cx += adv as i32 * scale as i32;
        }
        (width, height, rgba)
    }
}

static EXTERNAL_FONT: RwLock<Option<GlyphAtlas>> = RwLock::new(None);

/// Install `atlas` as the fallback glyph source consulted for every
/// codepoint the built-in font does not cover. Replaces any previous pack;
/// pass to [`clear_external_font`] to uninstall. The built-in tables always
/// win for covered codepoints, so installing a pack can only fill tofu gaps,
/// never change an existing glyph.
pub fn install_external_font(atlas: GlyphAtlas) {
    *EXTERNAL_FONT
        .write()
        .unwrap_or_else(|e| e.into_inner()) = Some(atlas);
}

/// Remove the installed external font pack.
pub fn clear_external_font() {
    *EXTERNAL_FONT
        .write()
        .unwrap_or_else(|e| e.into_inner()) = None;
}

/// Bitmap for `c` from the installed external pack, if any.
pub fn external_glyph(c: char) -> Option<GlyphBitmap> {
    EXTERNAL_FONT
        .read()
        .unwrap_or_else(|e| e.into_inner())
        .as_ref()
        .and_then(|atlas| atlas.glyph_bitmap(c))
}

/// Full 16-row un-squashed glyph for `c` from the installed external
/// pack, if it covers `c`.
pub fn external_unifont_glyph(c: char) -> Option<GlyphRows16> {
    EXTERNAL_FONT
        .read()
        .unwrap_or_else(|e| e.into_inner())
        .as_ref()
        .and_then(|atlas| atlas.unifont_glyph(c))
}

/// Vanilla `ascii.png` 8×8 bitmap for `c` from the installed external
/// pack, if a table was loaded.
pub fn external_ascii_glyph(c: char) -> Option<[u8; 8]> {
    EXTERNAL_FONT
        .read()
        .unwrap_or_else(|e| e.into_inner())
        .as_ref()
        .and_then(|atlas| atlas.ascii_glyph(c))
}
