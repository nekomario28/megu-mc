#!/usr/bin/env python3
"""Report how far the installed datapack is from the pinned 1.21.1 build's own data.

    tools/pack_provenance.py [--pack datapacks/vanilla] [--jar <server.jar>] [--quiet]

The reference worlds the fixtures compare against are generated by the pinned jar, so
the data the port loads should come from that same jar. It does not: the bundled pack
is 1.21.1 worldgen re-encoded in a much newer dialect (biomes carry `attributes`
mob-spawn blocks, noises carry `base_amplitude`/`octave_count`, densities use
`minecraft:gradient` with `axis`, noise settings moved the aquifers out of
`noise_router`). `feature/`, `placed_feature/`, `configured_carver/` and the provider
directories are byte-identical, so the conversion was partial.

This prints, per directory: files only in the jar, files only in the pack, byte-identical
and differing counts, and for the differing ones whether they are at least *semantically*
equal as JSON. A non-zero exit means the pack is not the pinned build's data.

Reading the jar neither extracts nor writes anything: the nested server jar is opened
from the outer one in memory.
"""
import argparse
import hashlib
import io
import json
import pathlib
import sys
import zipfile

PINNED_SHA1 = "59353fb40c36d304f2035d51e7d6e6baa98dc05c"
JAR_CANDIDATES = [
    "~/.cache/mc-spine-audit/load/vanilla/server.jar",
    "/data/lane-scratch/wg-oracle/server.jar",
    "/data/lane-scratch/mc-vanilla-eval/server.jar",
]
# The directories this port actually loads (see `Gen::dp_files` callers): a pack that
# omits structures, templates, world presets and flat presets is not a mismatch, so they
# are only counted for information.
LOADED = [
    "biome",
    "configured_carver",
    "configured_feature",
    "feature",
    "density_function",
    "material_condition",
    "material_rule",
    "noise",
    "noise_settings",
    "placed_feature",
    "block_state_provider",
]
NOT_LOADED = [
    "flat_level_generator_preset",
    "multi_noise_biome_source_parameter_list",
    "processor_list",
    "structure",
    "structure_set",
    "template_pool",
    "world_preset",
]
DIRS = LOADED

# The same directory under two names: 1.21.1 calls it `configured_feature`, the newer
# layout (and any pack converted from it) calls it `feature`. Comparing them as-is would
# report ~200 files as missing on both sides.
ALIASES = {"feature": "configured_feature"}


def find_jar(explicit):
    if explicit:
        return pathlib.Path(explicit).expanduser()
    for c in JAR_CANDIDATES:
        p = pathlib.Path(c).expanduser()
        if p.is_file():
            return p
    return None


def jar_pack(jar):
    """{relpath under data/minecraft: bytes} from the jar's own datapack."""
    out = {}
    with zipfile.ZipFile(jar) as outer:
        inner_name = next(
            (n for n in outer.namelist() if n.startswith("META-INF/versions/") and n.endswith(".jar")),
            None,
        )
        if inner_name is None:
            sys.exit(f"pack provenance: no nested server jar in {jar}")
        with zipfile.ZipFile(io.BytesIO(outer.read(inner_name))) as inner:
            for n in inner.namelist():
                if n.startswith("data/minecraft/worldgen/") and n.endswith(".json"):
                    out[n[len("data/minecraft/worldgen/") :]] = inner.read(n)
        # block tags matter too: they decide what a feature may replace
        with zipfile.ZipFile(io.BytesIO(outer.read(inner_name))) as inner:
            for n in inner.namelist():
                if n.startswith("data/minecraft/tags/block/") and n.endswith(".json"):
                    out["../tags/block/" + n[len("data/minecraft/tags/block/") :]] = inner.read(n)
    return out


def pack_files(root):
    out = {}
    for sub in DIRS:
        d = root / "data/minecraft/worldgen" / sub
        if not d.is_dir():
            continue
        for f in d.rglob("*.json"):
            key = str(pathlib.Path(sub) / f.relative_to(d))
            for alias, real in ALIASES.items():
                if key.startswith(alias + "/"):
                    key = real + key[len(alias) :]
            out[key] = f.read_bytes()
    d = root / "data/minecraft/tags/block"
    if d.is_dir():
        for f in d.rglob("*.json"):
            out["../tags/block/" + str(f.relative_to(d))] = f.read_bytes()
    return out


def same_json(a, b):
    try:
        return json.loads(a) == json.loads(b)
    except Exception:
        return False


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pack", default="datapacks/vanilla")
    ap.add_argument("--jar")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args()

    jar = find_jar(args.jar)
    if jar is None or not jar.is_file():
        sys.exit("pack provenance: no pinned server.jar found; pass --jar")
    got = hashlib.sha1(jar.read_bytes()).hexdigest()
    if got != PINNED_SHA1:
        sys.exit(f"pack provenance: {jar} is sha1 {got}, expected {PINNED_SHA1}")

    ref = jar_pack(jar)
    cur = pack_files(pathlib.Path(args.pack))
    print(f"pack provenance: {jar}")
    print(f"  jar: {len(ref)} files, pack: {len(cur)} files")

    per = {}
    only_jar, only_pack, identical, differ, sem = [], [], 0, [], 0
    for k in sorted(set(ref) | set(cur)):
        top = k.split("/")[0] if not k.startswith("../") else "../tags/block"
        if top in NOT_LOADED:
            continue
        ref_k, cur_k = k in ref, k in cur
        st = per.setdefault(top, {"only_jar": 0, "only_pack": 0, "identical": 0, "differ": 0, "sem": 0})
        if not cur_k:
            only_jar.append(k)
            st["only_jar"] += 1
        elif not ref_k:
            only_pack.append(k)
            st["only_pack"] += 1
        elif ref[k] == cur[k]:
            identical += 1
            st["identical"] += 1
        else:
            differ.append(k)
            st["differ"] += 1
            if same_json(ref[k], cur[k]):
                sem += 1
                st["sem"] += 1
    for top in sorted(per):
        st = per[top]
        print(
            f"  {top:<24} identical {st['identical']:>4}  differing {st['differ']:>4}"
            f" (json-equal {st['sem']:>4})  only-in-jar {st['only_jar']:>3}  only-in-pack {st['only_pack']:>3}"
        )
    if not args.quiet:
        print(f"  only in the jar (missing features the reference has): {len(only_jar)}")
        for k in only_jar[:8]:
            print(f"    {k}")
        print(f"  only in the pack (not part of 1.21.1): {len(only_pack)}")
        for k in only_pack[:8]:
            print(f"    {k}")
    print(f"  totals: identical {identical}, differing {len(differ)} (json-equal {sem})")
    if len(differ) or len(only_jar) or len(only_pack):
        print("  verdict: the pack is NOT the pinned build's own data")
        return 1
    print("  verdict: the pack matches the pinned build's own data")
    return 0


if __name__ == "__main__":
    sys.exit(main())
