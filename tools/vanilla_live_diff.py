def _vanilla_command(jar):
    """How to boot `jar`: a Mojang *bundler* jar runs via `java -jar`, while an
    already-unpacked inner `server-<version>.jar` needs its libraries on the
    classpath (a sibling `libraries/` + `versions/` tree, the layout a bundler
    extraction leaves behind)."""
    with zipfile.ZipFile(jar) as archive:
        names = archive.namelist()
        is_bundler = (any(n.startswith("META-INF/versions/")
                          for n in names)
                      and any(n.startswith("META-INF/libraries/")
                              and n.endswith(".jar") for n in names))
    if is_bundler:
        return ["java", "-Xmx1G", "-jar", str(jar), "nogui"]
    libs_root = jar.parent / "libraries"
    versions = sorted((jar.parent / "versions").glob("*/server-*.jar")) \
        if (jar.parent / "versions").is_dir() else []
    if libs_root.is_dir() and versions:
        classpath = os.pathsep.join(
            [str(versions[0])]
            + [str(p) for p in sorted(libs_root.rglob("*.jar"))])
        return ["java", "-Xmx1G", "-cp", classpath,
                "net.minecraft.server.Main", "nogui"]
    raise SetupError(
        f"{jar} is an unpacked inner server jar with no bundled libraries; "
        "pass the full Mojang bundler server.jar, or a jar whose parent "
        "directory already has extracted libraries/ and versions/ trees")


def _terminate(proc, graceful_wait=8):
    if proc.poll() is None:
        proc.terminate()
    try:
        proc.wait(timeout=graceful_wait)
    except subprocess.TimeoutExpired:
        proc.kill()
        proc.wait(timeout=5)


