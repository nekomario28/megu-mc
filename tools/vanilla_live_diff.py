def _play(ctx):
    """Connect with a short retry: a just-closed session can still be held
    server-side ("a player with that name or UUID is already logged in")."""
    last = None
    for _ in range(4):
        try:
            return Client.play(ctx.endpoint, ctx.name, ctx.deadline,
                               command_delay=ctx.command_delay)
        except ScenarioError as exc:
            last = exc
            if "already logged in" not in str(exc):
                raise
            time.sleep(0.75)
    raise last


