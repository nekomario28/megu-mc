def parse_block_update(body):
    """0x09 block_update: packed Position + VarInt block state id."""
    reader = Reader(body)
    x, y, z = unpack_position(reader.number(">Q"))
    state = reader.varint()
    return {"x": x, "y": y, "z": z, "state": state}


def parse_change_difficulty(body):
    """0x0b change_difficulty: u8 difficulty + bool locked."""
    reader = Reader(body)
    return {"difficulty": reader.number("B"),
            "locked": bool(reader.number("B"))}


def parse_game_event(body):
    """0x22 game_event: u8 event + f32 value."""
    reader = Reader(body)
    return {"event": reader.number("B"), "value": reader.number(">f")}


def parse_player_abilities(body):
    """0x38 player_abilities: u8 flags + f32 fly speed + f32 fov modifier."""
    reader = Reader(body)
    flags = reader.number("B")
    fly_speed = reader.number(">f")
    fov = reader.number(">f")
    return {"flags": flags, "invulnerable": bool(flags & 0x01),
            "flying": bool(flags & 0x02), "allow_flying": bool(flags & 0x04),
            "instabuild": bool(flags & 0x08), "fly_speed": fly_speed,
            "fov_modifier": fov}


def parse_player_position(body):
    """0x40 player_position: 3xd64, 2xf32, u8 flags, VarInt teleport id [, bool]."""
    reader = Reader(body)
    x = reader.number(">d")
    y = reader.number(">d")
    z = reader.number(">d")
    yaw = reader.number(">f")
    pitch = reader.number(">f")
    flags = reader.number("B")
    teleport_id = reader.varint()
    dismount = bool(reader.number("B")) if reader.remaining() else None
    return {"x": x, "y": y, "z": z, "yaw": yaw, "pitch": pitch,
            "flags": flags, "teleport_id": teleport_id, "dismount": dismount}


def parse_set_health(body):
    """0x5d set_health: f32 health + VarInt food + f32 saturation."""
    reader = Reader(body)
    return {"health": reader.number(">f"), "food": reader.varint(),
            "saturation": reader.number(">f")}


def parse_set_time(body):
    """0x64 set_time: i64 world age + i64 time of day."""
    reader = Reader(body)
    return {"world_age": reader.number(">q"), "day_time": reader.number(">q")}


def parse_update_mob_effect(body):
    """0x76 update_mob_effect: VarInt entity, VarInt effect, u8 amplifier,
    VarInt duration ticks, u8 flags, optional factor data."""
    reader = Reader(body)
    entity_id = reader.varint()
    effect_id = reader.varint()
    amplifier = reader.number("B")
    duration = reader.varint()
    flags = reader.number("B")
    has_factor_data = bool(reader.number("B")) if reader.remaining() else None
    return {"entity_id": entity_id, "effect_id": effect_id,
            "amplifier": amplifier, "duration": duration, "flags": flags,
            "has_factor_data": has_factor_data}


def parse_set_objective(body):
    """0x5e set_objective: String name + u8 mode (+ fields for create/update)."""
    reader = Reader(body)
    name = reader.string(16)
    mode = reader.number("B")
    return {"name": name, "mode": mode}


def parse_set_score(body):
    """0x61 set_score: String owner + String objective + VarInt value."""
    reader = Reader(body)
    owner = reader.string()
    objective = reader.string(16)
    value = reader.varint()
    return {"owner": owner, "objective": objective, "value": value}


def parse_add_entity(body):
    """0x01 add_entity: VarInt id + 16B uuid + VarInt type + 3xd64 pos + ..."""
    reader = Reader(body)
    entity_id = reader.varint()
    reader.take(16)  # uuid
    entity_type = reader.varint()
    x = reader.number(">d")
    y = reader.number(">d")
    z = reader.number(">d")
    return {"entity_id": entity_id, "entity_type": entity_type,
            "x": x, "y": y, "z": z}


def _parse_slot(reader):
    count = reader.varint()
    if count <= 0:
        return {"item": None, "count": count}
    item = reader.varint()
    return {"item": item, "count": count}


def parse_container_set_slot(body):
    """0x15 container_set_slot: u8 window + VarInt state + i16 slot + slot."""
    reader = Reader(body)
    window = reader.number("B")
    state_id = reader.varint()
    slot = reader.number(">h")
    parsed = _parse_slot(reader)
    return {"window": window, "state_id": state_id, "slot": slot,
            "item": parsed["item"], "count": parsed["count"]}


def parse_container_set_content(body):
    """0x13 container_set_content: u8 window + VarInt state + slot array."""
    reader = Reader(body)
    window = reader.number("B")
    state_id = reader.varint()
    length = reader.varint()
    slots = [_parse_slot(reader) for _ in range(min(length, 512))]
    return {"window": window, "state_id": state_id, "slots": slots}


def parse_login_play(body):
    """0x2b login (play): i32 entity id + u8 hardcore + dimension list."""
    reader = Reader(body)
    entity_id = reader.number(">i")
    hardcore = bool(reader.number("B"))
    return {"entity_id": entity_id, "hardcore": hardcore}


def parse_pong_response(body):
    """0x36 pong_response: i64 payload echoed from ping_request."""
    if len(body) != 8:
        raise WireError(f"pong_response length {len(body)} != 8")
    return struct.unpack(">q", body)[0]


