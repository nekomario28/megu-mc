def vint(value):
    out = bytearray()
    value &= 0xFFFFFFFF
    while True:
        b = value & 0x7F
        value >>= 7
        out.append(b | (0x80 if value else 0))
        if not value:
            return bytes(out)


def varlong(value):
    out = bytearray()
    value &= 0xFFFFFFFFFFFFFFFF
    while True:
        b = value & 0x7F
        value >>= 7
        out.append(b | (0x80 if value else 0))
        if not value:
            return bytes(out)


def mc_string(text):
    raw = text.encode("utf-8")
    return vint(len(raw)) + raw


def pack_position(x, y, z):
    return ((x & 0x3FFFFFF) << 38) | ((z & 0x3FFFFFF) << 12) | (y & 0xFFF)


def _signed(value, bits):
    return value - (1 << bits) if value & (1 << (bits - 1)) else value


def unpack_position(packed):
    return (_signed(packed >> 38, 26), _signed(packed & 0xFFF, 12),
            _signed((packed >> 12) & 0x3FFFFFF, 26))


def frame_packet(raw, threshold=-1):
    """Length-prefix `raw` (VarInt packet id + body) for the wire.

    Once Set Compression negotiates a non-negative threshold every frame is
    `VarInt(frame_len)` over `VarInt(data_len) + payload`, where `data_len` is
    0 for an uncompressed packet and the uncompressed length followed by the
    zlib stream otherwise.
    """
    if threshold >= 0:
        inner = (vint(0) + raw) if len(raw) < threshold else (
            vint(len(raw)) + zlib.compress(raw))
    else:
        inner = raw
    return vint(len(inner)) + inner


def unframe_packet(frame_data, threshold=-1):
    """Inverse of `frame_packet` for one received frame (prefix removed)."""
    if threshold < 0:
        return frame_data
    reader = Reader(frame_data)
    data_len = reader.varint()
    rest = reader.take(reader.remaining())
    if data_len == 0:
        if len(rest) >= threshold:
            raise WireError("uncompressed packet meets compression threshold")
        return rest
    if not 0 < data_len <= 16 * 1024 * 1024:
        raise WireError("invalid compressed data length")
    try:
        packet = zlib.decompress(rest)
    except zlib.error as exc:
        raise WireError(f"invalid zlib stream: {exc}") from exc
    if len(packet) != data_len:
        raise WireError("decompressed length mismatch")
    return packet


class Reader:
    def __init__(self, data):
        self.data, self.pos = data, 0

    def remaining(self):
        return len(self.data) - self.pos

    def take(self, n):
        if not 0 <= n <= self.remaining():
            raise WireError("truncated field")
        part = self.data[self.pos:self.pos + n]
        self.pos += n
        return part

    def number(self, fmt):
        return struct.unpack(fmt, self.take(struct.calcsize(fmt)))[0]

    def _var(self, limit):
        value = 0
        for i in range(limit):
            byte = self.number("B")
            value |= (byte & 127) << (7 * i)
            if not byte & 128:
                return value
        raise WireError("oversized variable integer")

    def varint(self):
        return self._var(5)

    def varlong(self):
        return self._var(10)

    def string(self, limit=1 << 20):
        raw = self.take(self.varint())
        if len(raw) > limit:
            raise WireError("oversized string")
        return raw.decode("utf-8", "replace")


class WireError(Exception):
    """Malformed packet or broken connection."""


class ScenarioError(Exception):
    """A scenario could not produce an observation (connect/login/disconnect)."""


class SetupError(Exception):
    """Fail-closed input error -> exit 2."""


def _recv_exact(sock, n):
    out = bytearray()
    while len(out) < n:
        chunk = sock.recv(n - len(out))  # socket.timeout propagates to caller
        if not chunk:
            raise WireError("unexpected EOF")
        out.extend(chunk)
    return bytes(out)


def recv_vint(sock):
    value = 0
    for i in range(5):
        byte = _recv_exact(sock, 1)[0]
        value |= (byte & 127) << (7 * i)
        if not byte & 128:
            return value
    raise WireError("oversized frame VarInt")


def offline_uuid(name):
    raw = bytearray(hashlib.md5(("OfflinePlayer:" + name).encode()).digest())
    raw[6] = (raw[6] & 15) | 48
    raw[8] = (raw[8] & 63) | 128
    return bytes(raw)


def dashed_uuid(raw):
    h = raw.hex()
    return f"{h[:8]}-{h[8:12]}-{h[12:16]}-{h[16:20]}-{h[20:]}"


