def free_port():
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


def _wait_listener(endpoint, proc, deadline, ready_check=None):
    while time.monotonic() < deadline:
        if proc.poll() is not None:
            raise SetupError(f"server exited during boot (rc={proc.returncode})")
        try:
            if ready_check is None:
                socket.create_connection(endpoint, timeout=1).close()
                return
            ready_check()
            return
        except (OSError, AssertionError, ScenarioError, WireError, ValueError,
                json.JSONDecodeError):
            time.sleep(0.15)
    raise SetupError("server listener did not become ready")


