def client_information(view=4):
    """Configuration C2S 0x00 client_information body."""
    return (vint(5) + b"en_us" + struct.pack("b", view) + vint(0)
            + b"\x01" + bytes([0x7F]) + vint(1) + b"\x00\x01")


def chat_command_body(text):
    """Play C2S chat_command (0x04): the bare unsigned command string.

    1.21.1 splits signed commands onto chat_command_signed (0x05); the
    unsigned packet carries no envelope fields at all -- verified against a
    live Vanilla 1.21.1 server (it disconnects with "20 bytes extra" if the
    signed envelope is appended here)."""
    return mc_string(text)


class Client:
    """One protocol-767 client connection with automatic play-phase answers.

    A daemon reader thread drains S2C frames in play phase, answers KeepAlive
    (0x26 -> 0x18), teleport confirm (0x40 -> 0x00), Ping (0x35 -> 0x27),
    chunk-batch pacing (0x0c -> 0x08) and records every packet on `events`.
    """

    def __init__(self, endpoint, name=BOT_NAME):
        self.endpoint = endpoint
        self.name = name
        self.command_delay = 0.22
        self.socket = socket.create_connection(endpoint, timeout=10)
        self.compression = -1
        self.phase = "handshake"
        self.events = []          # [(pid, body)] in arrival order
        self.cond = threading.Condition()
        self.disconnected = None  # reason string once the reader dies
        self.got_login_play = False
        self.got_position = False
        self._reader = None

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        self.close()

    def close(self):
        try:
            self.socket.shutdown(socket.SHUT_RDWR)
        except OSError:
            pass
        try:
            self.socket.close()
        except OSError:
            pass

    # -- low-level io --------------------------------------------------------

    def _send_raw(self, raw):
        self.socket.sendall(frame_packet(raw, self.compression))

    def send(self, pid, body=b""):
        self._send_raw(vint(pid) + body)

    def _read_packet(self, timeout):
        self.socket.settimeout(timeout)
        try:
            frame = _recv_exact(self.socket, recv_vint(self.socket))
        except socket.timeout as exc:
            raise WireError("read timeout") from exc
        packet = Reader(unframe_packet(frame, self.compression))
        return packet.varint(), packet.take(packet.remaining())

    def _fail_disconnect(self, pid, body):
        reason = body[:300].decode("utf-8", "replace")
        raise ScenarioError(f"disconnect packet 0x{pid:02x}: {reason}")

    # -- handshake / login / configuration -----------------------------------

    @classmethod
    def play(cls, endpoint, name=BOT_NAME, deadline=None, command_delay=0.22):
        client = cls(endpoint, name)
        client.command_delay = command_delay
        try:
            client._login(deadline if deadline is not None else
                          time.monotonic() + 30)
            client._start_reader()
            return client
        except BaseException:
            client.close()
            raise

    def _login(self, deadline):
        def left(cap=10):
            return max(0.1, min(cap, deadline - time.monotonic()))

        host = self.endpoint[0].encode()
        handshake = (vint(PROTOCOL) + vint(len(host)) + host
                     + struct.pack(">H", self.endpoint[1]) + vint(2))
        self.send(0x00, handshake)
        self.send(0x00, mc_string(self.name) + offline_uuid(self.name))
        # login phase: set_compression? -> login_success
        for _ in range(8):
            pid, body = self._read_packet(left())
            if pid == 0x03:      # set_compression
                threshold = Reader(body).varint()
                if not 0 <= threshold <= (1 << 21):
                    raise ScenarioError(f"invalid compression threshold {threshold}")
                self.compression = threshold
                continue
            if pid == 0x00:
                self._fail_disconnect(pid, body)
            if pid == 0x01:
                raise ScenarioError("encryption request on offline server")
            if pid == 0x02:      # login_success
                break
            if pid == 0x04:      # login_plugin_request -> negative response
                reader = Reader(body)
                self.send(0x02, reader.take(4) + b"\x00")
                continue
            raise ScenarioError(f"unexpected login packet 0x{pid:02x}")
        else:
            raise ScenarioError("login success never arrived")
        self.send(0x03)          # login_acknowledged
        self.phase = "configuration"
        self.send(0x00, client_information())
        answered_packs = False
        for _ in range(4096):
            pid, body = self._read_packet(left())
            if pid == 0x02:
                self._fail_disconnect(pid, body)
            if pid == 0x00:      # cookie_request
                reader = Reader(body)
                self.send(0x01, mc_string(reader.string()) + b"\x00")
            elif pid == 0x04:    # keep_alive
                self.send(0x04, body)
            elif pid == 0x05:    # ping
                self.send(0x05, body)
            elif pid == 0x0e and not answered_packs:  # select_known_packs
                self.send(0x07, vint(0))
                answered_packs = True
            elif pid == 0x09:    # resource_pack_push -> respond accepted
                self.send(0x06, body[:16] + vint(3))
            elif pid == 0x03:    # finish_configuration
                self.send(0x03)
                self.phase = "play"
                break
        else:
            raise ScenarioError("finish_configuration never arrived")
        # early play: wait for login + first position, answering flow control
        for _ in range(8192):
            pid, body = self._read_packet(left(20))
            self._handle_play(pid, body)
            if self.disconnected is not None:
                raise ScenarioError(self.disconnected)
            if self.got_login_play and self.got_position:
                return
        raise ScenarioError("play login never arrived")

    def _handle_play(self, pid, body):
        """Flow-control answers + event record for one play-phase packet."""
        try:
            if pid == S2C_KEEP_ALIVE:
                self.send(C2S_KEEP_ALIVE, body)
            elif pid == S2C_PLAYER_POSITION:
                teleport_id = parse_player_position(body)["teleport_id"]
                self.send(C2S_TELEPORT_CONFIRM, vint(teleport_id))
            elif pid == S2C_PING:
                self.send(C2S_PONG, body)
            elif pid == S2C_CHUNK_BATCH_FINISHED:
                self.send(C2S_CHUNK_BATCH_RECEIVED, struct.pack(">f", 30.0))
            elif pid == S2C_COOKIE_REQUEST:
                reader = Reader(body)
                self.send(0x11, mc_string(reader.string()) + b"\x00")
        except OSError:
            pass  # socket closing: the event below is still recorded
        if pid == S2C_PLAYER_POSITION:
            self.got_position = True
        elif pid == S2C_DISCONNECT:
            self.disconnected = f"play disconnect: {body[:200]!r}"
        elif pid == S2C_LOGIN_PLAY:
            self.got_login_play = True
        with self.cond:
            self.events.append((pid, body))
            self.cond.notify_all()

    def _start_reader(self):
        def loop():
            while True:
                try:
                    self.socket.settimeout(0.5)
                    try:
                        frame = _recv_exact(
                            self.socket, recv_vint(self.socket))
                    except socket.timeout:
                        continue  # idle poll interval, not a disconnect
                    packet = Reader(unframe_packet(frame, self.compression))
                    pid, body = packet.varint(), packet.take(packet.remaining())
                except (WireError, OSError) as exc:
                    with self.cond:
                        if self.disconnected is None:
                            self.disconnected = f"reader ended: {exc}"
                        self.cond.notify_all()
                    return
                self._handle_play(pid, body)

        self._reader = threading.Thread(target=loop, daemon=True,
                                        name="vdiff-reader")
        self._reader.start()

    # -- scenario surface ----------------------------------------------------

    def baseline(self):
        with self.cond:
            return len(self.events)

    def events_since(self, base):
        with self.cond:
            return list(self.events[base:])

    def wait_event(self, pred, timeout, base=0):
        """First (pid, body) at index >= base satisfying pred, or None."""
        end = time.monotonic() + timeout
        scan = base
        with self.cond:
            while True:
                while scan < len(self.events):
                    pid, body = self.events[scan]
                    scan += 1
                    if pred(pid, body):
                        return pid, body
                if self.disconnected is not None:
                    return None
                remaining = end - time.monotonic()
                if remaining <= 0:
                    return None
                self.cond.wait(remaining)

    def collect_last(self, pred, timeout, base, tail=0.3):
        """Every (pid, body) at index >= base satisfying pred until `timeout`,
        shrinking to a `tail` drain once the first match lands. Returns the
        last match or None -- "last" is the right read for packets a server
        may emit both at login and again in answer to a command."""
        end = time.monotonic() + timeout
        scan = base
        found = []
        while time.monotonic() < end and self.disconnected is None:
            for pid, body in self.events_since(scan):
                scan += 1
                if pred(pid, body):
                    found.append((pid, body))
            if found:
                end = min(end, time.monotonic() + tail)
            else:
                time.sleep(0.02)
        return found[-1] if found else None

    def settled_baseline(self, settle):
        """Baseline after the post-login packet burst (initial set_time,
        change_difficulty, abilities, game_event 13, ...) has had `settle`
        seconds to land, so a later command answer cannot be shadowed."""
        time.sleep(settle)
        return self.baseline()

    def command(self, text):
        self.send(C2S_CHAT_COMMAND, chat_command_body(text))
        time.sleep(self.command_delay)  # chat-rate pacing for both servers

    def ping_request(self, payload):
        # Play ping_request carries an i64 payload (verified against live
        # Vanilla 1.21.1: int/varint bodies fail to decode and get kicked).
        self.send(C2S_PING_REQUEST, struct.pack(">q", payload))


def _status_frame(pid, body=b""):
    packet = vint(pid) + body
    return vint(len(packet)) + packet


def status_probe(endpoint, timeout=10):
    """Status-phase handshake: (protocol_version, pong_echo_ok)."""
    sock = socket.create_connection(endpoint, timeout=timeout)
    try:
        sock.settimeout(timeout)
        host = endpoint[0].encode()
        handshake = (vint(PROTOCOL) + vint(len(host)) + host
                     + struct.pack(">H", endpoint[1]) + vint(1))
        sock.sendall(_status_frame(0x00, handshake) + _status_frame(0x00))
        packet = Reader(_recv_exact(sock, recv_vint(sock)))
        if packet.varint() != 0x00:
            raise ScenarioError("no status_response")
        info = json.loads(packet.string())
        payload = 0x1122334455667788
        sock.sendall(_status_frame(0x01, struct.pack(">q", payload)))
        pong = Reader(_recv_exact(sock, recv_vint(sock)))
        echo_ok = (pong.varint() == 0x01
                   and struct.unpack(">q", pong.take(8))[0] == payload)
        return int(info.get("version", {}).get("protocol", -1)), echo_ok
    finally:
        sock.close()


