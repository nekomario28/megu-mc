FLOAT_TOL = 1e-3

# Per-field comparison tolerances: `/time set 6000` pins day_time to exactly
# 6000 but the value keeps ticking at the world's own cadence, so a few ticks
# of drift between the two servers' observation instants is environmental,
# not a parity defect. A server that never applied the command stays near
# its pre-command time and still diffs.
FIELD_TOLERANCES = {"day_time_mod": 40.0, "x": 1e-3, "y": 1e-3, "z": 1e-3}


def _values_equal(observed, reference, field=None):
    if observed is None or reference is None:
        return observed == reference
    tol = FIELD_TOLERANCES.get(field, FLOAT_TOL)
    if isinstance(reference, float) or isinstance(observed, float) \
            or tol != FLOAT_TOL:
        try:
            return abs(float(observed) - float(reference)) <= tol
        except (TypeError, ValueError):
            return False
    if isinstance(reference, bool) or isinstance(observed, bool):
        return bool(observed) == bool(reference)
    return observed == reference


class _Context:
    def __init__(self, endpoint, deadline, per_wait, command_delay, settle,
                 tail):
        self.endpoint = endpoint
        self.name = BOT_NAME
        self.deadline = deadline
        self.per_wait = per_wait
        self.command_delay = command_delay
        self.settle = settle
        self.tail = tail


def run_scenario(name, ctx):
    func = dict((n, f) for n, f, _ in SCENARIOS)[name]
    return func(ctx)


def run_differential(megu_endpoint, vanilla_endpoint=None, timeout=120,
                     per_wait=None, command_delay=0.22, settle=0.8, tail=0.3,
                     progress=None):
    """Run all scenarios; return a report dict.

    `megu_endpoint` / `vanilla_endpoint` are (host, port) tuples of already
    listening servers. Each scenario's observation is compared field-by-field:
    megu-vs-vanilla when both servers are given, else megu-vs-EXPECTED (the
    Vanilla 1.21.1 reference constants above).
    """
    deadline = time.monotonic() + timeout
    if per_wait is None:
        per_wait = max(2.0, min(15.0, timeout / 8.0))
    megu_obs, vanilla_obs = {}, {}

    def run_all(endpoint):
        out = {}
        for name, _func, _exp in SCENARIOS:
            ctx = _Context(endpoint, deadline, per_wait, command_delay,
                           settle, tail)
            try:
                out[name] = run_scenario(name, ctx)
            except (ScenarioError, WireError, OSError, TimeoutError,
                    json.JSONDecodeError) as exc:
                out[name] = exc
            if progress:
                progress(name)
            if time.monotonic() > deadline:
                for later, _f, _e in SCENARIOS:
                    out.setdefault(later, ScenarioError("global timeout"))
                break
        return out

    # The two servers are independent: sweep them in parallel to halve the
    # wall time of a dual run (each scenario still runs sequentially).
    if vanilla_endpoint is not None:
        vanilla_thread = threading.Thread(
            target=lambda: vanilla_obs.update(run_all(vanilla_endpoint)),
            daemon=True, name="vdiff-vanilla-sweep")
        vanilla_thread.start()
        megu_obs = run_all(megu_endpoint)
        vanilla_thread.join()
    else:
        megu_obs = run_all(megu_endpoint)

    results = []
    matched = 0
    for name, _func, expected in SCENARIOS:
        entry = {"scenario": name, "fields": {}}
        megu_val = megu_obs.get(name)
        if isinstance(megu_val, Exception):
            entry.update(status="ERROR", error=str(megu_val))
            results.append(entry)
            continue
        if vanilla_endpoint is not None:
            van_val = vanilla_obs.get(name)
            if isinstance(van_val, Exception):
                entry.update(status="ERROR",
                             error=f"vanilla: {van_val}")
                results.append(entry)
                continue
            keys = [k for k in expected if k in megu_val or k in van_val]
            keys += [k for k in megu_val if k not in keys and not k.startswith("_")]
            diffs = []
            for key in keys:
                mv, vv = megu_val.get(key), van_val.get(key)
                entry["fields"][key] = {"megu": mv, "vanilla": vv}
                if not _values_equal(mv, vv, field=key):
                    diffs.append(key)
            entry["status"] = "MATCH" if not diffs else "DIFF"
            entry["diff_fields"] = diffs
        else:
            diffs = []
            for key, exp in expected.items():
                mv = megu_val.get(key)
                entry["fields"][key] = {"megu": mv, "expected": exp}
                if not _values_equal(mv, exp, field=key):
                    diffs.append(key)
            entry["status"] = "MATCH" if not diffs else "DIFF"
            entry["diff_fields"] = diffs
        if entry["status"] == "MATCH":
            matched += 1
        results.append(entry)

    return {"schema": SCHEMA, "mode": "dual" if vanilla_endpoint else "megu",
            "matched": matched, "total": len(SCENARIOS), "results": results}


def _parse_endpoint(text):
    host, sep, port = text.rpartition(":")
    if not sep or not host:
        raise SetupError(f"invalid endpoint {text!r}; expected host:port")
    return host, int(port)


def _fmt_value(value):
    if isinstance(value, float):
        return f"{value:.4g}"
    return repr(value)


def text_report(report):
    lines = [f"vanilla_live_diff ({report['mode']} mode)"]
    for entry in report["results"]:
        name, status = entry["scenario"], entry["status"]
        if status == "ERROR":
            lines.append(f"  {name:<24} ERROR  {entry['error']}")
            continue
        if status == "MATCH":
            lines.append(f"  {name:<24} MATCH")
            continue
        lines.append(f"  {name:<24} DIFF")
        for key in entry.get("diff_fields", []):
            cells = entry["fields"][key]
            ref_key = "vanilla" if "vanilla" in cells else "expected"
            lines.append(f"      {key:<22} megu={_fmt_value(cells['megu'])}"
                         f" {ref_key}={_fmt_value(cells[ref_key])}")
    lines.append(f"  score: {report['matched']}/{report['total']} scenarios MATCH")
    return "\n".join(lines)


