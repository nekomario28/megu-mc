// Protocol 777 (Minecraft 26.3) canonical name tables.
//
// Packet ids are transcribed from the MIT-licensed `horizon-protocol` `ids.rs`
// (generated from the vanilla 26.3 DataGenerator `packets` report). Packet
// names keep this crate's convention — the Mojang name minus its
// `Clientbound`/`Serverbound` prefix — so names the canonical codec resolves
// (`handshake`, `encryption_request`, `login_success`, `set_compression`,
// `keep_alive`, `registry_data`, `open_screen`, `set_equipment`,
// `set_passengers`, `set_player_team`, `tab_list`, `ticking_state`,
// `ticking_step`, `player_input`, `move_vehicle`, `paddle_boat`, `light_update`
// …) match what `data_v767.rs` calls the same semantic packets; the report
// spells them `intention`/`hello`/`login_finished`/`login_compression` etc.
//
// Registries: `minecraft:menu` carries the menu types the canonical IR models,
// in vanilla's append-stable registry order (verified identical between the
// 1.21.1 report and the names 26.3 code resolves). `minecraft:data_component_type`
// is deliberately the codec-facing subset — exactly the component names
// `codec::skip_component_value` has wire shapes for, in their 1.21.x relative
// order — NOT the full 26.3 registry. The full 26.3 `minecraft:block`,
// `minecraft:item`, `minecraft:entity_type` and complete component tables are
// DataGenerator-report data and land through
// `ProtocolTable::from_version_pack_json`; leaving them absent here means a
// cross-version session remap fails closed instead of guessing 26.3 ids.
